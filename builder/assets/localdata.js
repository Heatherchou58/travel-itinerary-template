/* 氣候判定：看月份與緯度絕對值，南半球月份對調 */
export function climateOf(month, lat){
  const south = lat < 0;
  const m = south ? ((month + 5) % 12) + 1 : month;
  const abs = Math.abs(lat);
  const out = [];
  if (abs < 25){                                  // 熱帶／亞熱帶，全年偏熱
    out.push("hot");
    if (m >= 5 && m <= 10) out.push("rainy");     // 多數熱帶地區的雨季
  } else if (m === 12 || m <= 2){
    out.push("cold");
    if (abs > 35) out.push("snowy");
  } else if (m >= 6 && m <= 8){
    out.push("hot");
    if (abs < 40) out.push("rainy");              // 東亞梅雨與颱風季
  } else {
    out.push("cool");
  }
  return out;
}

